export async function seedCountries(strapi) {
  for (const country of COUNTRIES) {
    const existing = await strapi.db.query('api::country.country').findOne({
      where: { code: country.code },
    });
    if (existing) continue;

    await strapi.documents('api::country.country').create({
      data: {
        code: country.code,
        name: country.name,
        flag: country.flag,
        hreflang: country.hreflang,
        isDefault: country.isDefault,
        heroTitle: country.heroTitle,
        heroSubtitle: country.heroSubtitle,
        seoDescription: country.seoDescription,
        sortOrder: country.sortOrder,
      },
      ...(ENABLED.has(country.code) ? { status: 'published' } : {}),
    });
    strapi.log.info(`[seed] Created country edition ${country.code}`);
  }
}
